# 3. 토큰 개수 계산
def tokenize(text):

    if pd.isna(text):
        return []

    text = str(text).strip()

    if text == "":
        return []

    return text.split()

check_results = []

for category, models in model_config.items():

    category_df = preprocess_df[
        preprocess_df["category"] == category
    ]

    for model_name, text_column in models.items():

        if text_column not in preprocess_df.columns:
            print(f"⚠️ 컬럼 없음: {text_column}")
            continue

        for _, row in category_df.iterrows():

            tokens = tokenize(row[text_column])

            token_count = len(tokens)

            # 이론적으로 생성되어야 하는 개수
            expected_1gram = max(token_count, 0)
            expected_2gram = max(token_count - 1, 0)
            expected_3gram = max(token_count - 2, 0)

            check_results.append({
                "category": category,
                "model": model_name,
                "product_id": row["product_id"],
                "image_order": row["image_order"],
                "token_count": token_count,
                "expected_1gram": expected_1gram,
                "expected_2gram": expected_2gram,
                "expected_3gram": expected_3gram
            })

token_check = pd.DataFrame(check_results)

