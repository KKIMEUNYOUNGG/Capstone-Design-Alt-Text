import ast
import re

def convert_to_tokens(value):

    if pd.isna(value):
        return []

    value = str(value).strip()

    if value == "":
        return []

    # 문자열로 저장된 리스트를 실제 리스트로 변환
    if value.startswith("[") and value.endswith("]"):
        try:
            tokens = ast.literal_eval(value)

            if isinstance(tokens, list):
                cleaned_tokens = []

                for token in tokens:
                    token = str(token).strip()

                    # 토큰 양쪽의 불필요한 기호 제거
                    token = token.strip("[]'\" ,")

                    if token:
                        cleaned_tokens.append(token)

                return cleaned_tokens

        except (ValueError, SyntaxError):
            pass

    # 리스트 형태가 아닌 경우
    tokens = value.split()

    cleaned_tokens = []

    for token in tokens:
        token = token.strip("[]'\" ,")

        if token:
            cleaned_tokens.append(token)

    return cleaned_tokens

# 4.N-gram 생성
def make_ngrams(tokens, n):

    if len(tokens) < n:
        return []

    return [
        " ".join(tokens[i:i+n])
        for i in range(len(tokens) - n + 1)
    ]

