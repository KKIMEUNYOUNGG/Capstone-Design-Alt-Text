# 5. 카테고리별 N-gram 생성
# =========================================================

def generate_ngram(df, model_config, n):

    results = []

    for category, models in model_config.items():

        category_df = df[
            df["category"] == category
        ].copy()

        print(f"\n[{category}]")
        print(f"데이터 수: {len(category_df)}")

        for model_name, text_column in models.items():

            print(f"  모델: {model_name}")
            print(f"  사용 컬럼: {text_column}")

            if text_column not in df.columns:
                print(f"  ⚠️ 컬럼이 존재하지 않습니다: {text_column}")
                continue

            for _, row in category_df.iterrows():

                # 전처리된 토큰 가져오기
                tokens = convert_to_tokens(
                    row[text_column]
                )

                # N-gram 생성
                ngrams = make_ngrams(
                    tokens,
                    n
                )

                # 동일 N-gram의 등장 횟수 계산
                ngram_counts = Counter(ngrams)

                # 결과 저장
                for keyword, count in ngram_counts.items():

                    results.append({
                        "category": row["category"],
                        "model": model_name,
                        "product_id": row["product_id"],
                        "image_order": row["image_order"],
                        "n_gram_keyword": keyword,
                        "ngram_count": count
                    })

    return pd.DataFrame(results)

# 1-gram
