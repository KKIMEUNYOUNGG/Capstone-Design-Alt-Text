#3. 토큰화 함수 만들기
def tokenize(text):

    # 결측값 처리
    if pd.isna(text):
        return []

    # 문자열로 변환
    text = str(text).strip()

    # 빈 문자열 처리
    if text == "":
        return []

    # 공백 기준으로 토큰 분리
    return text.split()

# 4.N-gram 생성
def make_ngrams(tokens, n):

    # 토큰 수가 N보다 적으면 생성할 수 없음
    if len(tokens) < n:
        return []

    # N-gram 생성
    ngrams = [
        " ".join(tokens[i:i+n])
        for i in range(len(tokens) - n + 1)
    ]

    return ngrams

